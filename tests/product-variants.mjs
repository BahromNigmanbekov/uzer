import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {stripTypeScriptTypes} from "node:module";
import vm from "node:vm";
const source=stripTypeScriptTypes(readFileSync("lib/product-variants.ts","utf8"));
const names=[...source.matchAll(/export (?:const|function) (\w+)/g)].map(match=>match[1]);
const api=vm.runInNewContext(`(()=>{${source.replace(/export (?=const|function)/g,"")}\nreturn {${names.join(",")}}})()`);
const products=JSON.parse(readFileSync("tests/fixtures/legacy-products.json","utf8"));
const product=id=>products.find(p=>p.id===String(id));
const models=api.groupedProducts(products);
assert.equal(models.length,7);
for(const [category,id] of [["T-Shirt","29"],["Hoodie","15"],["Zip Hoodie","25"],["Bag","41"]])assert.equal(models.find(p=>p.category===category).id,id);
assert.equal(api.productVariants(products,product(27)).length,8);
assert.equal(api.productVariants(products,product(35)).length,5);
assert.equal(api.productVariants(products,product(11)).length,6);
assert.equal(api.productVariants(products,product(23)).length,4);
assert.equal(api.colorOf(product(35)),"iceblue");assert.equal(api.colorOf(product(38)),"beige");assert.equal(api.colorOf(product(23)),"charcoal");
assert.ok(api.familyKey(product(35))!==api.familyKey(product(27)),"printed and plain T-shirts must not mix");
const filtered=products.filter(p=>api.colorOf(p)==="pink");
assert.ok(api.groupedProducts(filtered).every(p=>api.colorOf(p)==="pink"),"filtered cards must open a matching variant");
assert.equal(api.productVariants(products.map(p=>p.id==="28"?{...p,active:false}:p),product(27)).length,7);
assert.equal(api.groupedProducts([{...product(27),id:"custom-a",title:"Unique model A",images:[]},{...product(27),id:"custom-b",title:"Unique model B",images:[]}]).length,2);
assert.deepEqual(products.map(p=>p.id),Array.from({length:43},(_,i)=>String(i+1)),"source stock/order identity is untouched");
console.log("PASS: 43 SKUs in 7 model families; dark defaults, real photo colors, matching filters and independent stock IDs");
